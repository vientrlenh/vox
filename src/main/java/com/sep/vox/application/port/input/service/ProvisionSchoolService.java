package com.sep.vox.application.port.input.service;

import com.sep.vox.domain.model.user.Role;
import java.time.Instant;
import java.util.UUID;

import lombok.RequiredArgsConstructor;
import org.springframework.stereotype.Service;

import com.sep.vox.application.event.UserCreatedPayloadV1;
import com.sep.vox.application.exception.ResourceDuplicatedException;
import com.sep.vox.application.exception.ResourceNotFoundException;
import com.sep.vox.application.port.input.command.school.ProvisionSchoolCommand;
import com.sep.vox.application.port.output.JsonSerializationPort;
import com.sep.vox.domain.common.AggregateTypeConstant;
import com.sep.vox.domain.common.EventTypeConstant;
import com.sep.vox.domain.common.UserTypeConstant;
import com.sep.vox.domain.model.outbox.Outbox;
import com.sep.vox.domain.model.school.School;
import com.sep.vox.domain.model.school.SchoolUser;
import com.sep.vox.domain.model.user.User;
import com.sep.vox.domain.model.user.UserRole;
import com.sep.vox.domain.repository.OutboxRepository;
import com.sep.vox.domain.repository.RoleRepository;
import com.sep.vox.domain.repository.SchoolRepository;
import com.sep.vox.domain.repository.SchoolUserRepository;
import com.sep.vox.domain.repository.UserRepository;
import com.sep.vox.domain.repository.UserRoleRepository;

@Service
@RequiredArgsConstructor
public class ProvisionSchoolService {
    
    private final UserRepository userRepository;
    private final RoleRepository roleRepository;
    private final SchoolRepository schoolRepository;
    private final SchoolUserRepository schoolUserRepository;
    private final UserRoleRepository userRoleRepository;
    private final OutboxRepository outboxRepository;
    private final JsonSerializationPort jsonSerializationPort;

    /** @return the id of the school just created. */
    public UUID provision(ProvisionSchoolCommand command) {
        Role schoolAdminRole = roleRepository.findByCode("SCHOOL_ADMIN")
            .orElseThrow(() -> new ResourceNotFoundException("School admin role not found"));

        requireNoDuplicate(command);

        School savedSchool = saveSchool(command);
        User savedSchoolAdmin = saveSchoolAdmin(command,  savedSchool.getId());
        saveSchoolAdminUserRole(command, savedSchoolAdmin.getId(), schoolAdminRole.getId());

        SchoolUser schoolUser = SchoolUser.create(savedSchoolAdmin.getId(), savedSchool.getId(), command.now(), null);
        schoolUserRepository.save(schoolUser);

        publishSchoolAdminCreated(command, savedSchoolAdmin.getId());

        return savedSchool.getId();
    }

    private void requireNoDuplicate(ProvisionSchoolCommand command) {
        if (userRepository.existsByEmail(command.contactEmail())) {
            throw new ResourceDuplicatedException("A user with this email already exists");
        }

        if (userRepository.existsByPhone(command.contactPhone())) {
            throw new ResourceDuplicatedException("A user with this phone number already exists");
        }

        if (schoolRepository.existsByCode(command.schoolCode())) {
            throw new ResourceDuplicatedException("School code already exists");
        }
    }

    /**
     * The password-setting token is generated by the consumer right before the mail is sent, so it is never
     * plaintext in the outboxes table or in the Kafka topic.
     */
    private void publishSchoolAdminCreated(ProvisionSchoolCommand command, UUID schoolAdminId) {
        UserCreatedPayloadV1 event = new UserCreatedPayloadV1(
            schoolAdminId,
            command.contactEmail(),
            command.contactFullName(),
            command.schoolName(),
            UserTypeConstant.SCHOOL_ADMIN
        );
        String payload = jsonSerializationPort.toJson(event);
        Outbox outbox = Outbox.create(
            AggregateTypeConstant.USER, schoolAdminId, EventTypeConstant.USER_CREATED, payload, Instant.now());
        outboxRepository.save(outbox);
    }

    private School saveSchool(ProvisionSchoolCommand command) {
        School school = School.create(
            command.schoolCode(), 
            command.schoolName(), 
            command.description(), 
            command.contactPhone(), 
            command.contactEmail(), 
            command.schoolDomain(), 
            command.schoolAddress(), 
            command.studentCount()
        );
        return schoolRepository.save(school);
    }

    private User saveSchoolAdmin(ProvisionSchoolCommand command, UUID schoolId) {
        User schoolAdmin = User.createSchoolAdmin(
            command.contactEmail(),  
            command.contactPhone(), 
            command.contactFullName(), 
            command.dateOfBirth(), 
            command.contactAddress(), 
            command.avatarUrl()
        );
        return userRepository.save(schoolAdmin);
    }

    private void saveSchoolAdminUserRole(ProvisionSchoolCommand command, UUID schoolAdminId, UUID schoolAdminRoleId) {
        userRoleRepository.save(UserRole.assigned(schoolAdminId, schoolAdminRoleId, command.now()));
    }
}
