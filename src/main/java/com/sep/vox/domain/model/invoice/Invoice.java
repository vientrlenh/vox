package com.sep.vox.domain.model.invoice;

import java.time.Instant;
import java.util.UUID;

import com.sep.vox.domain.common.ZoneConstant;

/**
 * Only completed orders are invoiced (business rule normalized).
 * Invoices are no longer used to record the process of paying an order (this used to be hard-coded inside a
 * subscription order).
 * Every operation on a request goes through the Orders entity.
 * It now also covers the invoice of a request to top up the school's account (used to pay for the part of the
 * plan's quota that has been fully consumed).
 * Invoice
 */
public class Invoice {
    private UUID id; 
    private UUID orderId;
    private UUID paymentId; // Only the latest successful payment attempt is taken
    private String invoiceNumber;
    private Instant issueDate;

    public Invoice() {}



    public UUID getId() {
        return id;
    }

    public void setId(UUID id) {
        this.id = id;
    }

    public UUID getOrderId() {
        return orderId;
    }

    public void setOrderId(UUID orderId) {
        this.orderId = orderId;
    }

    public UUID getPaymentId() {
        return paymentId;
    }

    public void setPaymentId(UUID paymentId) {
        this.paymentId = paymentId;
    }

    public String getInvoiceNumber() {
        return invoiceNumber;
    }

    public void setInvoiceNumber(String invoiceNumber) {
        this.invoiceNumber = invoiceNumber;
    }

    public Instant getIssueDate() {
        return issueDate;
    }

    public void setIssueDate(Instant issueDate) {
        this.issueDate = issueDate;
    }

    /**
     * Issues the document for an order that has been fully paid.
     *
     * <p>The invoice number is generated BY THE YEAR OF THE ISSUE DATE, taken in the business time zone: issuing at 23:30
     * on 31/12 Vietnam time is still the old year, while at the same instant UTC is already in the new year -- taking the
     * wrong one would produce an invoice numbered INV-2027-... but dated 31/12/2026.
     *
     * <p>The suffix comes from a random UUID rather than an increasing counter: a counter needs one shared lock row for
     * the whole system, and this is the path that runs inside the webhook transaction -- a lock there would make every
     * callback queue up behind the others.
     *
     * <p>LONG ENOUGH to never rely on the unique constraint. That constraint is still there and still blocks, but it
     * fires INSIDE the transaction of {@code OrderSettlementService.settlePaid} -- rolling back the PAID attempt, the
     * order's SUCCESS status and the delivery (crediting the wallet or activating the plan) together, for an order whose
     * money really has arrived. There is no retry loop here, so a collision means waiting for PendingOrderReconciler to
     * come back and roll the dice again.
     *
     * <p>That is why it takes 48 bits (12 hex characters) instead of the 8 characters of the first version. By the
     * birthday paradox, 8 characters (~4.3 billion values) already have ~1% chance of a collision at 10,000 invoices a
     * year and 50% at about 77,000 -- well within reach. 48 bits (~2.8 x 10^14) pushes that 50% mark to about 20 million
     * invoices a year, so the rollback case no longer happens in practice.
     *
     * <p>Taken from {@code getLeastSignificantBits}: the 2 variant bits of a UUID v4 sit at the top of the low half and
     * the 4 version bits are in the high half -- the 48-bit mask below therefore keeps 48 TRULY RANDOM bits, whereas
     * cutting from the high half would include 4 fixed bits.
     */
    public static Invoice issueFor(UUID orderId, UUID paymentId, Instant issuedAt) {
        int year = issuedAt.atZone(ZoneConstant.BUSINESS_ZONE).getYear();
        String suffix = "%012X".formatted(UUID.randomUUID().getLeastSignificantBits() & 0xFFFF_FFFF_FFFFL);
        return builder()
            .orderId(orderId)
            .paymentId(paymentId)
            .invoiceNumber("INV-" + year + "-" + suffix)
            .issueDate(issuedAt)
            .build();
    }

    public static Builder builder() {
        return new Builder();
    }

    public static class Builder {

        private final Invoice target = new Invoice();

        private Builder() {
        }

        public Builder id(UUID id) {
            target.id = id;
            return this;
        }

        public Builder orderId(UUID orderId) {
            target.orderId = orderId;
            return this;
        }

        public Builder paymentId(UUID paymentId) {
            target.paymentId = paymentId;
            return this;
        }

        public Builder invoiceNumber(String invoiceNumber) {
            target.invoiceNumber = invoiceNumber;
            return this;
        }

        public Builder issueDate(Instant issueDate) {
            target.issueDate = issueDate;
            return this;
        }

        public Invoice build() {
            return target;
        }

    }
}
