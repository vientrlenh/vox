package com.sep.vox.infrastructure.persistence.entity.personalization;

import java.time.Instant;
import java.util.UUID;

import org.hibernate.annotations.UuidGenerator;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.Id;
import jakarta.persistence.Table;
import lombok.AccessLevel;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.experimental.SuperBuilder;

@Entity
@Table(name = "interest_quiz_items")
@Getter
@Setter
@SuperBuilder
@NoArgsConstructor(access = AccessLevel.PROTECTED)
public class InterestQuizItemJpaEntity {

    @Id
    @UuidGenerator(style = UuidGenerator.Style.VERSION_7)
    @Column(name = "id", nullable = false, updatable = false)
    private UUID id;

    @Column(name = "dimensions_json", nullable = false, columnDefinition = "TEXT")
    private String dimensionsJson;

    @Column(name = "statements_json", nullable = false, columnDefinition = "TEXT")
    private String statementsJson;

    // TEXT: text generated by the LLM, no length ceiling -- see the comment in V15__personalize.sql
    // (section 18. interest_quiz_items).
    @Column(name = "desirability_note", columnDefinition = "TEXT")
    private String desirabilityNote;

    @Column(name = "active", nullable = false)
    @Builder.Default
    private boolean active = true;

    // NULL = the shared static/original set (fallback); a value = generated specifically for this student
    // (package 13 "situation-based quiz generation", see task/implement/13-...).
    @Column(name = "student_id")
    private UUID studentId;

    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;
}
