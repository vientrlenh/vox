package com.sep.vox.infrastructure.persistence.repository;

import java.util.Collection;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

import org.springframework.data.jpa.repository.JpaRepository;

import com.sep.vox.infrastructure.persistence.entity.payment.PaymentRecordJpaEntity;

public interface SpringDataPaymentRecordRepository extends JpaRepository<PaymentRecordJpaEntity, UUID> {
    List<PaymentRecordJpaEntity> findByOrderId(UUID orderId);

    /**
     * Sorted right here rather than letting the upper layer sort again: the batch loader only groups by order_id,
     * and groupingBy keeps the stream order, so the right order must already come from the query.
     *
     * <p>Ordered by {@code id} and not by {@code created_at}, and this is ONLY CORRECT because id is generated by
     * {@code uuidv7()} -- the first 48 bits are a millisecond timestamp, so comparing uuids in Postgres is also
     * comparing time. In exchange we get a UNIQUE sort key (the primary key), meaning the order is already total
     * with no need for a tiebreaker like {@code createdAt DESC, id DESC} in
     * {@code SpringDataOrderRepository.findForAdmin}.
     *
     * <p>The constraint that keeps this true is in {@code PaymentRecordJpaEntity.id}:
     * {@code insertable = false} plus {@code DEFAULT uuidv7()} means the application can NEVER set
     * the id itself. Whoever changes that default, or inserts directly with SQL using a chosen id, breaks the order here
     * silently instead of with an error -- so a change must go back to {@code createdAt}.
     */
    List<PaymentRecordJpaEntity> findByOrderIdInOrderByIdDesc(Collection<UUID> orderIds);
    Optional<PaymentRecordJpaEntity> findByProviderAndProviderOrderRef(String provider, String providerOrderRef);
    Optional<PaymentRecordJpaEntity> findByOrderIdAndStatus(UUID orderId, String status);
    List<PaymentRecordJpaEntity> findByStatus(String status);
    long countByOrderId(UUID orderId);
}
