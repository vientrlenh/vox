package com.sep.vox.interfaces.rest.config;

import org.springdoc.core.customizers.OperationCustomizer;
import org.springdoc.core.service.OpenAPIService;
import org.springframework.context.annotation.Bean;
import org.springframework.context.annotation.Configuration;

import io.swagger.v3.oas.models.Components;
import io.swagger.v3.oas.models.OpenAPI;
import io.swagger.v3.oas.models.info.Info;
import io.swagger.v3.oas.models.security.SecurityRequirement;
import io.swagger.v3.oas.models.security.SecurityScheme;

@Configuration
public class OpenApiConfig {

    private static final String TITLE = "Vox API v1";
    private static final String VERSION = "1.0.0";
    private static final String DESCRIPTION = "Vox API Documentation for AI Oral Assessment Evaluation System";
    private static final String SECURITY_SCHEME_NAME = "bearerAuth";
    private static final String SECURITY_SCHEME = "bearer";
    private static final String BEARER_FORMAT = "JWT";
    private static final String REST_CONTROLLER_PREFIX = "Rest";
    private static final String REST_TAG_PREFIX = "rest-";
    
    @Bean
    public OpenAPI applicationOpenAPI() {
        return new OpenAPI()
            .info(new Info()
                .title(TITLE)
                .version(VERSION)
                .description(DESCRIPTION))
            .addSecurityItem(new SecurityRequirement()
                .addList(SECURITY_SCHEME_NAME))
            .components(new Components()
                .addSecuritySchemes(SECURITY_SCHEME_NAME, new SecurityScheme()
                    .name(SECURITY_SCHEME_NAME)
                    .type(SecurityScheme.Type.HTTP)
                    .scheme(SECURITY_SCHEME)
                    .bearerFormat(BEARER_FORMAT)));
    }

    /**
     * Keeps the generated tag of a REST controller as it was before the controllers got the
     * {@code Rest} prefix, so clients generated by tag are not affected: {@code RestAssessmentController}
     * is tagged {@code assessment-controller}, not {@code rest-assessment-controller}.
     */
    @Bean
    public OperationCustomizer unprefixedRestTagCustomizer() {
        return (operation, handlerMethod) -> {
            String simpleName = handlerMethod.getBeanType().getSimpleName();
            if (simpleName.startsWith(REST_CONTROLLER_PREFIX) && operation.getTags() != null) {
                String generatedTag = OpenAPIService.splitCamelCase(simpleName);
                operation.setTags(operation.getTags().stream()
                    .map(tag -> tag.equals(generatedTag) ? tag.substring(REST_TAG_PREFIX.length()) : tag)
                    .toList());
            }
            return operation;
        };
    }
}
