package com.sep.vox.architecture;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * Keeps the conventions of the base-model audit refactoring: every model has a builder, audit actors are
 * {@code String} values written by Spring Data auditing, entity ids are generated by Hibernate, and entities live in
 * feature sub-packages.
 *
 * <p>The checks scan source text because most of these rules (a text in a column definition, a setter call on a
 * variable) leave nothing for ArchUnit to inspect. Each check asserts that it scanned enough files, so a broken
 * pattern cannot pass by matching nothing.
 *
 * <p>The exemption lists below name the classes that decision D2 of the plan left out of {@code BaseModel} and
 * {@code BaseEntity} because they do not own the full set of audit fields. An exemption that no longer applies makes
 * the test fail, so the lists cannot silently grow stale.
 */
class ModelAndEntityConventionTests {

    private static final Path MAIN_ROOT = Path.of("src/main/java/com/sep/vox");

    private static final Path MODEL_DIR = MAIN_ROOT.resolve("domain/model");

    private static final Path ENTITY_DIR = MAIN_ROOT.resolve("infrastructure/persistence/entity");

    private static final List<Path> MANUAL_STAMP_DIRS =
        List.of(MAIN_ROOT.resolve("application"), MAIN_ROOT.resolve("infrastructure/worker"));

    private static final String BASE_ENTITY_FILE_NAME = "BaseEntity.java";

    private static final Pattern CONCRETE_MODEL_CLASS = Pattern.compile("(?m)^public\\s+(?:final\\s+)?class\\s+(\\w+)");

    private static final Pattern UUID_AUDIT_ACTOR_FIELD =
        Pattern.compile("\\bUUID\\s+(?:createdBy|updatedBy)\\s*;");

    private static final Pattern MANUAL_AUDIT_SETTER =
        Pattern.compile("\\.set(?:CreatedBy|UpdatedBy|CreatedAt|UpdatedAt)\\(");

    private static final Pattern DATABASE_GENERATED_ID = Pattern.compile("uuidv7\\(");

    /** D2: these classes keep plain UUID actor fields because they are not part of the audited set of 36. */
    private static final Set<String> UUID_ACTOR_FIELD_EXEMPTIONS = Set.of(
        "AssessmentCandidate.java",
        "AssessmentItemRuleHit.java",
        "AssessmentCandidateJpaEntity.java",
        "AssessmentItemRuleHitJpaEntity.java");

    /** D2: these files stamp objects whose class is not audited, so persistence does not stamp them. */
    private static final Set<String> MANUAL_STAMP_EXEMPTIONS = Set.of(
        "UnblockAssessmentCandidateUseCase.java",
        "UpdateAssessmentCandidatesAttendanceUseCase.java",
        "UpdateAssessmentCandidateStatusUseCase.java",
        "ClearInvalidResultUseCase.java",
        "ForceEndAssessmentSessionUseCase.java",
        "AssessmentStatusAutoTransitionJob.java");

    @Test
    @DisplayName("every concrete domain model class has a public static builder()")
    void every_model_class_has_a_builder() throws IOException {
        List<String> offenders = new ArrayList<String>();
        int scanned = 0;

        for (Path file : javaFilesUnder(MODEL_DIR)) {
            String source = readWithoutComments(file);
            Matcher declaration = CONCRETE_MODEL_CLASS.matcher(source);
            if (!declaration.find() || hasPrivateNoArgumentConstructor(source, declaration.group(1))) {
                continue;
            }
            scanned++;
            if (!source.contains("public static Builder builder()")) {
                offenders.add(file.getFileName() + " has no public static Builder builder()");
            }
        }

        assertScannedEnoughAndNoOffenders(scanned, 90, "model classes", offenders,
            "every model is built through builder(), never through a positional constructor");
    }

    @Test
    @DisplayName("no model or entity declares a UUID createdBy or updatedBy field")
    void audit_actors_are_not_uuid_fields() throws IOException {
        List<Path> files = new ArrayList<Path>(javaFilesUnder(MODEL_DIR));
        files.addAll(javaFilesUnder(ENTITY_DIR));

        List<String> offenders = filesMatching(files, UUID_AUDIT_ACTOR_FIELD, UUID_ACTOR_FIELD_EXEMPTIONS);

        assertThat(files.size()).as("model and entity files scanned").isGreaterThan(200);
        assertThat(offenders).as("audit actors are String values: a user id or \"System\"").isEmpty();
        assertThat(staleExemptions(files, UUID_AUDIT_ACTOR_FIELD, UUID_ACTOR_FIELD_EXEMPTIONS))
            .as("exempted files that no longer declare a UUID actor field: remove them from the exemption list")
            .isEmpty();
    }

    @Test
    @DisplayName("no entity text mentions uuidv7(): ids are generated by Hibernate")
    void entities_do_not_rely_on_database_generated_ids() throws IOException {
        List<Path> files = javaFilesUnder(ENTITY_DIR);

        List<String> offenders = filesMatching(files, DATABASE_GENERATED_ID, Set.of());

        assertThat(files.size()).as("entity files scanned").isGreaterThan(100);
        assertThat(offenders).as("entities use @UuidGenerator(style = VERSION_7), not a column default").isEmpty();
    }

    @Test
    @DisplayName("every entity except BaseEntity lives in a feature sub-package")
    void entities_live_in_feature_sub_packages() throws IOException {
        List<String> offenders = new ArrayList<String>();
        try (Stream<Path> files = Files.list(ENTITY_DIR)) {
            files.filter(path -> path.toString().endsWith(".java"))
                .filter(path -> !path.getFileName().toString().equals(BASE_ENTITY_FILE_NAME))
                .forEach(path -> offenders.add(path.getFileName() + " is directly in the entity package"));
        }

        assertThat(Files.exists(ENTITY_DIR.resolve(BASE_ENTITY_FILE_NAME))).as("BaseEntity stays in entity/").isTrue();
        assertThat(javaFilesUnder(ENTITY_DIR).size()).as("entity files scanned").isGreaterThan(100);
        assertThat(offenders).as("move the entity into entity/<feature>/").isEmpty();
    }

    @Test
    @DisplayName("application and workers never stamp createdBy, updatedBy, createdAt or updatedAt by hand")
    void audit_values_are_not_set_by_hand() throws IOException {
        List<Path> files = new ArrayList<Path>();
        for (Path directory : MANUAL_STAMP_DIRS) {
            files.addAll(javaFilesUnder(directory));
        }

        List<String> offenders = filesMatching(files, MANUAL_AUDIT_SETTER, MANUAL_STAMP_EXEMPTIONS);

        assertThat(files.size()).as("application and worker files scanned").isGreaterThan(300);
        assertThat(offenders).as("Spring Data auditing writes the audit values when the entity is saved").isEmpty();
        assertThat(staleExemptions(files, MANUAL_AUDIT_SETTER, MANUAL_STAMP_EXEMPTIONS))
            .as("exempted files that no longer stamp by hand: remove them from the exemption list")
            .isEmpty();
    }

    private static void assertScannedEnoughAndNoOffenders(
        int scanned, int minimumScanned, String scannedDescription, List<String> offenders, String rule) {
        assertThat(scanned)
            .as("number of " + scannedDescription + " scanned -- a low number means the check is fooling itself")
            .isGreaterThan(minimumScanned);
        assertThat(offenders).as(rule).isEmpty();
    }

    private static boolean hasPrivateNoArgumentConstructor(String source, String className) {
        return source.contains("private " + className + "()");
    }

    private static List<String> filesMatching(List<Path> files, Pattern pattern, Set<String> exemptFileNames)
        throws IOException {
        List<String> offenders = new ArrayList<String>();
        for (Path file : files) {
            Matcher matcher = pattern.matcher(readWithoutComments(file));
            if (matcher.find() && !exemptFileNames.contains(file.getFileName().toString())) {
                offenders.add(file.getFileName() + ": `" + matcher.group() + "`");
            }
        }
        return offenders;
    }

    private static List<String> staleExemptions(List<Path> files, Pattern pattern, Set<String> exemptFileNames)
        throws IOException {
        List<String> stale = new ArrayList<String>(exemptFileNames);
        for (Path file : files) {
            if (pattern.matcher(readWithoutComments(file)).find()) {
                stale.remove(file.getFileName().toString());
            }
        }
        return stale;
    }

    private static List<Path> javaFilesUnder(Path directory) throws IOException {
        try (Stream<Path> files = Files.walk(directory)) {
            return files.filter(path -> path.toString().endsWith(".java")).toList();
        }
    }

    private static String readWithoutComments(Path file) throws IOException {
        String source = Files.readString(file, StandardCharsets.UTF_8);
        return source.replaceAll("(?s)/\\*.*?\\*/", "").replaceAll("(?m)//[^\n]*", "");
    }
}
