package com.sep.vox.infrastructure.persistence.query;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.grpc.test.autoconfigure.AutoConfigureTestGrpcTransport;
import org.springframework.transaction.annotation.Transactional;

import com.sep.vox.domain.model.metering.QuotaType;
import com.sep.vox.domain.model.school.SchoolDebtEvent;
import com.sep.vox.domain.model.school.SchoolDebtEventType;
import com.sep.vox.domain.repository.SchoolDebtEventRepository;
import com.sep.vox.support.IntegrationTest;

import jakarta.persistence.EntityManager;

/**
 * {@code chk_school_debt_events_shape_matches_event_type} keeps the two halves of the V4 fix from drifting apart:
 * if a source column is added but the id is not passed down to the place that emits the event, the INSERT must fail
 * right away instead of silently writing one more row that has lost its trail.
 *
 * <p>The constraint lives in the database, so no Java-level check can reach it -- the row has to be pushed to a real
 * Postgres to know whether it guards correctly. It must also be declared in the {@code @Table} of
 * SchoolDebtEventJpaEntity: the test profile runs ddl-auto=create-drop, so the schema these tests face is built by
 * Hibernate from the annotations, not by Flyway from the migrations.
 *
 * <p>NOTE on where the exception surfaces: {@code flush()}, not {@code save()}. The id is generated by Hibernate
 * ({@code @UuidGenerator}), so {@code save()} only queues the INSERT and the database rejects the row when the queue
 * is flushed. That is why the rejecting tests go through {@link #saveAndFlush}.
 *
 * <p>See SchoolBalanceQuerySmokeTests for why this uses {@code @SpringBootTest} instead of a slice.
 */
@IntegrationTest
@AutoConfigureTestGrpcTransport
@Transactional
class SchoolDebtEventShapeTests {

    private static final String SHAPE_CONSTRAINT = "chk_school_debt_events_shape_matches_event_type";

    @Autowired
    private SchoolDebtEventRepository schoolDebtEventRepository;

    @Autowired
    private EntityManager entityManager;

    private final UUID schoolId = UUID.randomUUID();
    private final UUID subscriptionId = UUID.randomUUID();
    private final Instant now = Instant.parse("2026-08-29T10:00:00Z");

    @Test
    void should_accept_a_cleared_row_with_no_quota_bucket_and_no_trigger() {
        // Debt clearance is a SCHOOL-level event: the balance is ONE number shared by both quota
        // wallets, so no wallet has "just cleared its debt". Those three columns must be allowed to
        // stay empty, otherwise the event emitter is forced to invent a value and pollute the very
        // ledger used for reconciliation.
        SchoolDebtEvent saved = schoolDebtEventRepository.save(SchoolDebtEvent.builder()
            .schoolId(schoolId)
            .subscriptionId(subscriptionId)
            .eventType(SchoolDebtEventType.CLEARED)
            .quotaType(null)
            .triggerAssessmentSessionId(null)
            .triggerPracticeSessionId(null)
            .triggerAmountVnd(null)
            .totalAllocatedVnd(null)
            .usedAmountVnd(null)
            .overageVnd(BigDecimal.ZERO)
            .occurredAt(now)
            .build());

        assertThat(saved.getQuotaType()).isNull();
        assertThat(saved.getTriggerAssessmentSessionId()).isNull();
        assertThat(saved.getTriggerPracticeSessionId()).isNull();
        assertThat(saved.getOverageVnd()).isEqualByComparingTo(BigDecimal.ZERO);
    }

    @Test
    void should_accept_a_debt_row_triggered_by_a_practice_session() {
        // Exactly the shape that could not be written before V4: debt arising from a SPEAKING
        // PRACTICE session.
        SchoolDebtEvent saved = schoolDebtEventRepository.save(SchoolDebtEvent.builder()
            .schoolId(schoolId)
            .subscriptionId(subscriptionId)
            .eventType(SchoolDebtEventType.CAP_EXCEEDED)
            .quotaType(QuotaType.PRACTICE)
            .triggerAssessmentSessionId(null)
            .triggerPracticeSessionId(UUID.randomUUID())
            .triggerAmountVnd(new BigDecimal("18402.60"))
            .totalAllocatedVnd(new BigDecimal("2400000"))
            .usedAmountVnd(new BigDecimal("2906310"))
            .overageVnd(new BigDecimal("506310"))
            .occurredAt(now)
            .build());

        assertThat(saved.getTriggerPracticeSessionId()).isNotNull();
        assertThat(saved.getTriggerAssessmentSessionId()).isNull();
    }

    @Test
    void should_reject_a_cleared_row_that_claims_a_quota_bucket() {
        assertThatThrownBy(() -> saveAndFlush(SchoolDebtEvent.builder()
            .schoolId(schoolId)
            .subscriptionId(subscriptionId)
            .eventType(SchoolDebtEventType.CLEARED)
            .quotaType(QuotaType.ASSESSMENT)
            .triggerAssessmentSessionId(null)
            .triggerPracticeSessionId(null)
            .triggerAmountVnd(null)
            .totalAllocatedVnd(new BigDecimal("8000000"))
            .usedAmountVnd(new BigDecimal("8000000"))
            .overageVnd(BigDecimal.ZERO)
            .occurredAt(now)
            .build()))
            .hasMessageContaining(SHAPE_CONSTRAINT);
    }

    @Test
    void should_reject_a_debt_row_with_no_trigger_session_at_all() {
        // This is EXACTLY the row that the pre-V4 version could still write: a CAP_EXCEEDED caused by speaking practice, but
        // trigger_assessment_session_id = NULL because practiceSessionId was not passed down. The ledger knew the
        // school exceeded the ceiling but not because of which expense.
        assertThatThrownBy(() -> saveAndFlush(SchoolDebtEvent.builder()
            .schoolId(schoolId)
            .subscriptionId(subscriptionId)
            .eventType(SchoolDebtEventType.CAP_EXCEEDED)
            .quotaType(QuotaType.PRACTICE)
            .triggerAssessmentSessionId(null)
            .triggerPracticeSessionId(null)
            .triggerAmountVnd(new BigDecimal("18402.60"))
            .totalAllocatedVnd(new BigDecimal("2400000"))
            .usedAmountVnd(new BigDecimal("2906310"))
            .overageVnd(new BigDecimal("506310"))
            .occurredAt(now)
            .build()))
            .hasMessageContaining(SHAPE_CONSTRAINT);
    }

    @Test
    void should_reject_a_debt_row_naming_both_trigger_sessions() {
        assertThatThrownBy(() -> saveAndFlush(SchoolDebtEvent.builder()
            .schoolId(schoolId)
            .subscriptionId(subscriptionId)
            .eventType(SchoolDebtEventType.LOCKED)
            .quotaType(QuotaType.ASSESSMENT)
            .triggerAssessmentSessionId(UUID.randomUUID())
            .triggerPracticeSessionId(UUID.randomUUID())
            .triggerAmountVnd(new BigDecimal("96320.40"))
            .totalAllocatedVnd(new BigDecimal("8000000"))
            .usedAmountVnd(new BigDecimal("8045180"))
            .overageVnd(new BigDecimal("45180"))
            .occurredAt(now)
            .build()))
            .hasMessageContaining(SHAPE_CONSTRAINT);
    }

    @Test
    void should_reject_a_cleared_row_that_still_carries_a_debt() {
        // overage_vnd = 0 is the DEFINITION of "debt cleared", not a convenient default value.
        assertThatThrownBy(() -> saveAndFlush(SchoolDebtEvent.builder()
            .schoolId(schoolId)
            .subscriptionId(subscriptionId)
            .eventType(SchoolDebtEventType.CLEARED)
            .quotaType(null)
            .triggerAssessmentSessionId(null)
            .triggerPracticeSessionId(null)
            .triggerAmountVnd(null)
            .totalAllocatedVnd(null)
            .usedAmountVnd(null)
            .overageVnd(new BigDecimal("45180"))
            .occurredAt(now)
            .build()))
            .hasMessageContaining(SHAPE_CONSTRAINT);
    }

    private void saveAndFlush(SchoolDebtEvent event) {
        schoolDebtEventRepository.save(event);
        entityManager.flush();
    }
}
